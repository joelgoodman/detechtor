test('a short real page with a title is not contentless, and a long page mentioning maintenance is fine', () => {
  const shortReal = shell('Records Department | Riverside', '<h1>Records</h1><p>Request a transcript or a degree verification here.</p>');
  assert.deepStrictEqual(classifyCapture(shortReal), { scannable: true, reason: null });
  const notice = `<html><head><title>IT Status | Riverside</title></head><body><p>Canvas is down for maintenance on Sunday.</p><p>${FILLER}</p></body></html>`;
  assert.deepStrictEqual(classifyCapture(notice), { scannable: true, reason: null });
});
