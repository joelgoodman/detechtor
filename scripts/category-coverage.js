#!/usr/bin/env node
/**
 * Category audit coverage report (UNI-235)
 * ========================================
 * Reports what the category audit actually covered — and, more importantly, what it did NOT.
 *
 * This exists because of how UNI-233 ended: it closed as Done with its semantic layer at 4 of 994
 * technologies, roughly 0.4%, and nothing in the ticket said so. A reader saw a closed ticket and
 * reasonably concluded the categories were audited. The number that mattered lived only in a
 * comment. So this file generates the honest accounting from LIVE state rather than a snapshot —
 * rerun it any time and it tells you the truth as of now, including the parts that are still wrong.
 *
 * Usage:
 *   node scripts/category-coverage.js            # write docs/category-coverage.md
 *   node scripts/category-coverage.js --print    # also print the summary to stdout
 */
'use strict';
const fs = require('fs');
const path = require('path');
const DeTECHtor = require('../src/detechtor.js');
const { mapCategory, SIGNAL_CATEGORIES } = require('../src/category-mapping.js');
const OVERRIDES = require('../patterns/category-overrides.json');
const ALIASES = require('../patterns/technology-aliases.json');

const ROOT = path.resolve(__dirname, '..');
const prevPath = path.join(ROOT, 'docs/corpus-prevalence.json');
const prevalence = fs.existsSync(prevPath) ? JSON.parse(fs.readFileSync(prevPath, 'utf8')) : null;
const deferredPath = path.join(ROOT, 'docs/uni-235-deferred-findings.json');
const deferred = fs.existsSync(deferredPath) ? JSON.parse(fs.readFileSync(deferredPath, 'utf8')) : { pattern_suspect: [], name_overclaims: [] };

const engine = new DeTECHtor();
const raw = (d) => (d.categories || d.cats) || [];
const techs = Object.entries(engine.patterns).filter(([n, d]) => n !== '_metadata' && d && typeof d === 'object');
const overridden = new Set(Object.keys(OVERRIDES.overrides || {}));

// --- distribution --------------------------------------------------------------------------
const byCat = new Map();
const firingByCat = new Map();
let firing = 0;
for (const [name, def] of techs) {
  const insts = prevalence ? (prevalence.counts[name] || 0) : 0;
  if (insts) firing++;
  for (const c of new Set(raw(def).map(mapCategory))) {
    byCat.set(c, (byCat.get(c) || 0) + 1);
    if (insts) firingByCat.set(c, (firingByCat.get(c) || 0) + 1);
  }
}

const unclassified = byCat.get('Unclassified') || 0;
const pct = (n, d) => (d ? ((100 * n) / d).toFixed(1) + '%' : '—');

const L = [];
L.push('# Category audit — coverage report');
L.push('');
L.push('_Generated by `npm run audit:coverage` from live state. Rerun it; do not trust a stale copy._');
L.push('');
L.push('## What was covered');
L.push('');
L.push('| | |');
L.push('|---|---:|');
L.push(`| Technologies in the engine | ${techs.length.toLocaleString()} |`);
L.push(`| Carrying a reviewed category decision | ${overridden.size.toLocaleString()} (${pct(overridden.size, techs.length)}) |`);
L.push(`| Duplicate names merged away | ${Object.keys(ALIASES.aliases || {}).length} |`);
if (prevalence) {
  L.push(`| Fire on ≥1 institution | ${firing.toLocaleString()} of ${techs.length.toLocaleString()} (${pct(firing, techs.length)}) |`);
  L.push(`| Corpus measured against | ${prevalence.scanned.toLocaleString()} scannable institutions |`);
}
L.push(`| Examined but **not identifiable** (\`Unclassified\`) | ${unclassified.toLocaleString()} |`);
L.push('');

// --- signal categories ---------------------------------------------------------------------
L.push('## Signal categories');
L.push('');
L.push('These are what the product acts on and what a scorecard reports to a customer. A false');
L.push('positive here is visible to someone paying for it.');
L.push('');
L.push('| Category | Technologies | Of which fire |');
L.push('|---|---:|---:|');
for (const c of [...SIGNAL_CATEGORIES].sort()) {
  L.push(`| ${c} | ${byCat.get(c) || 0} | ${firingByCat.get(c) || 0} |`);
}
L.push('');

// --- full distribution ---------------------------------------------------------------------
L.push('## Full distribution');
L.push('');
L.push('| Category | Technologies | Of which fire |');
L.push('|---|---:|---:|');
for (const [c, n] of [...byCat].sort((a, b) => b[1] - a[1])) {
  L.push(`| ${SIGNAL_CATEGORIES.has(c) ? '**' + c + '**' : c} | ${n} | ${firingByCat.get(c) || 0} |`);
}
L.push('');

// --- the honest part -----------------------------------------------------------------------
L.push('## What this audit does NOT tell you');
L.push('');
L.push('Read this section before quoting any number above.');
L.push('');
L.push('**It cannot detect a false-positive pattern.** The audit asks whether a technology sits in');
L.push('the right category. It is blind to whether the technology is being detected correctly. Ask');
L.push('any reviewer "is Ghost correctly categorised as CMS?" and the answer is yes — Ghost genuinely');
L.push('is a CMS. Meanwhile its pattern is `html:["ghost"]`, which matches every `btn-ghost` CSS class');
L.push('on every page, and it "fires" on 15.8% of universities. **The category is right and the');
L.push('detection is garbage, and nothing in this audit can see that.** Those go to UNI-237.');
L.push('');
L.push(`**${deferred.pattern_suspect.length} suspected over-broad patterns** and`);
L.push(`**${deferred.name_overclaims.length} names that over-claim** were collected as a side effect and`);
L.push('recorded in `docs/uni-235-deferred-findings.json`. They are NOT fixed here.');
L.push('');
L.push('**Prevalence is homepage-only.** A technology firing on zero institutions has not been proven');
L.push('absent — it may live on interior pages (UNI-225) or be present and undetected. Zero means');
L.push('deprioritised, never absent.');
L.push('');
L.push('**Most decisions were machine-made.** Categories were adjudicated by batched model review');
L.push('with human adjudication on the consequential and contested cases. That is a real review, but');
L.push('it is not the same as a human having read all ' + techs.length.toLocaleString() + ' rows, and it should not be');
L.push('described as if it were.');
L.push('');
L.push('**A reviewer\'s "OK" is weaker evidence than its "FLAG".** Measured, not assumed: a pass that');
L.push('flagged wrongly-filed entries accurately then waved through image CDNs and lazy-loading');
L.push('utilities as "JavaScript frameworks". Re-checking only the approvals overturned 29 of 74.');
L.push('Any future audit of this shape must re-check what passed, not only what failed.');
L.push('');
L.push('**Known-wrong and not fixed.** `Reveal.js` (a presentation library) and `Stitches` (CSS-in-JS)');
L.push('survived a strict re-audit and are still filed as JavaScript frameworks. Left because they fire');
L.push('on 5 and 0 institutions respectively — diminishing returns, not correctness.');
L.push('');
L.push(`**\`Unclassified\` is ${unclassified.toLocaleString()} technologies we examined and could not identify.** That is`);
L.push('deliberate and it is an improvement: previously they made confident false claims ("this is a');
L.push('JavaScript framework"). Now they assert nothing. It is an invitation to identify them, not a');
L.push('finished state.');
L.push('');
L.push('**Being irrelevant is not being wrong.** `Reviews` and `Shipping & Logistics` were reviewed and');
L.push('changed nothing: they hold genuine review platforms and genuine parcel carriers. No university');
L.push('runs them, but they are correctly categorised. Whether we should carry those patterns at all is');
L.push('a different question, and it belongs to UNI-237.');
L.push('');

const out = path.join(ROOT, 'docs/category-coverage.md');
fs.writeFileSync(out, L.join('\n'));
if (process.argv.includes('--print')) console.log(L.join('\n'));
console.log(`wrote ${out}`);
console.log(`${techs.length} technologies · ${overridden.size} with a reviewed decision · ${unclassified} unclassified · ${firing} firing`);
